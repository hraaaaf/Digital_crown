MAX_FIXTURE_BYTES = 512 * 1024
_SQLITE_HEADER = b"SQLite format 3\x00"
_MARKER = "DIGITAL_CROWN_V15_05_6_SYNTHETIC_FIXTURE_V1"


class SyntheticFileRefused(ValueError):
    """No identifiers or source file content in exception text."""


@dataclass(frozen=True)
class SyntheticFileResult:
    mode: str
    source_sha256: str
    source_patients: int
    source_appointments: int
    verified_patients: int
    verified_appointments: int
    verified_patient_links: int
    orphan_appointments: int
    cross_tenant_links: int
    after_rollback_patients: int
    after_rollback_appointments: int
    source_persisted: bool = False
    cabinet_rows_read: bool = False
    cabinet_rows_written: bool = False
    import_permitted: bool = False

    def to_dict(self):
        return asdict(self)


def _fake_patient(i: int):
    return (
        10001 + i,
        "SYNTHETIC_ONLY_FIRST_%03d" % i,
        "SYNTHETIC_ONLY_LAST_%03d" % i,
        "2000-03-%02d" % (1 + i % 28),
        "F" if i % 2 else "M",
        "synthetic%03d@example.invalid" % i,
    )


def _fake_appointment(i: int):
    return (
        50001 + i,
        10001 + i // 2,
        "2026-11-%02d %02d:30" % (1 + i % 28, 8 + i % 9),
        "planned",
    )


def build_synthetic_fixture_bytes() -> bytes:
    """Downloadable reproducible SQLite file; contains absolutely no PHI."""
    db = sqlite3.connect(":memory:")
    try:
        db.executescript("""
CREATE TABLE dc_fixture_marker (version TEXT NOT NULL);
CREATE TABLE legacy_patients (
    id INTEGER PRIMARY KEY, first_name TEXT NOT NULL, last_name TEXT NOT NULL,
    birth_date TEXT NOT NULL, sex TEXT NOT NULL, email TEXT NOT NULL
);
CREATE TABLE legacy_appointments (
    id INTEGER PRIMARY KEY, patient_ref INTEGER NOT NULL,
    scheduled_at TEXT NOT NULL, status TEXT NOT NULL
);
""")
        db.execute("INSERT INTO dc_fixture_marker(version) VALUES (?)", (_MARKER,))
        db.executemany("INSERT INTO legacy_patients VALUES (?,?,?,?,?,?)",
                       (_fake_patient(i) for i in range(100)))
        db.executemany("INSERT INTO legacy_appointments VALUES (?,?,?,?)",
                       (_fake_appointment(i) for i in range(200)))
        db.commit()
        result = db.serialize()
        if not result.startswith(_SQLITE_HEADER) or len(result) > MAX_FIXTURE_BYTES:
            raise SyntheticFileRefused("INTERNAL_SYNTHETIC_FIXTURE_INVALID")
        return result
    finally:
        db.close()


def _read_exact_fixture(payload: bytes):
    if (not isinstance(payload, bytes) or
            not _SQLITE_HEADER == payload[:16] or
            not 0 < len(payload) <= MAX_FIXTURE_BYTES):
        raise SyntheticFileRefused("INVALID_SQLITE_FIXTURE_HEADER_OR_SIZE")
    # A cryptographic byte-for-byte allowlist is stricter than checking only
    # a spoofable test marker or column prefixes: no real database accepted.
    expected = build_synthetic_fixture_bytes()
    if not hmac.compare_digest(sha256(payload).digest(), sha256(expected).digest()):
        raise SyntheticFileRefused("ONLY_OFFICIAL_SYNTHETIC_FIXTURE_ACCEPTED")
    source = sqlite3.connect(":memory:")
    try:
        source.deserialize(payload)
        source.execute("PRAGMA trusted_schema=OFF")
        source.execute("PRAGMA query_only=ON")
        if source.execute("PRAGMA integrity_check").fetchone() != ("ok",):
            raise SyntheticFileRefused("SYNTHETIC_SQLITE_INTEGRITY_FAILURE")
        inventory = source.execute(
            "SELECT type, name FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' "
            "ORDER BY type,name"
        ).fetchall()
        if inventory != [
            ("table", "dc_fixture_marker"),
            ("table", "legacy_appointments"),
            ("table", "legacy_patients"),
        ]:
            raise SyntheticFileRefused("UNEXPECTED_SYNTHETIC_SQLITE_SCHEMA")
        marker = source.execute("SELECT version FROM dc_fixture_marker").fetchall()
        if marker != [(_MARKER,)]:
            raise SyntheticFileRefused("INVALID_SYNTHETIC_MARKER")
        ps = source.execute(
            "SELECT id,first_name,last_name,birth_date,sex,email "
            "FROM legacy_patients ORDER BY id"
        ).fetchall()
        aps = source.execute(
            "SELECT id,patient_ref,scheduled_at,status "
            "FROM legacy_appointments ORDER BY id"
        ).fetchall()
        if len(ps) != 100 or len(aps) != 200:
            raise SyntheticFileRefused("SYNTHETIC_ROW_COUNT_INVALID")
        if ps != [_fake_patient(i) for i in range(100)]:
            raise SyntheticFileRefused("SYNTHETIC_PATIENT_CONTENT_CHANGED")
        if aps != [_fake_appointment(i) for i in range(200)]:
            raise SyntheticFileRefused("SYNTHETIC_APPOINTMENT_CONTENT_CHANGED")
        return ps, aps
    except sqlite3.DatabaseError as err:
        raise SyntheticFileRefused("SYNTHETIC_SQLITE_READ_FAILED") from err
    finally:
        source.close()


def rehearse_uploaded_synthetic_sqlite(payload: bytes, declared_metadata):
    """Read real fake bytes, remap all 200 links, then rollback in RAM.

    This is NOT the real #869 E2E clinical importer; the authenticated
    staff gateway remains structurally preflight-only for real cabinet data.
    """
    ps, aps = _read_exact_fixture(payload)
    subset = _declared_subset(declared_metadata)
    engine = create_engine("sqlite+pysqlite:///:memory:", future=True)
    @event.listens_for(engine, "connect")
    def enable_foreign_keys(conn, _rec):
        cursor=conn.cursor()
        cursor.execute("PRAGMA foreign_keys=ON")
        cursor.close()
    try:
        with engine.connect() as db:
            subset.create_all(db)
            db.commit()
            if db.exec_driver_sql("PRAGMA foreign_keys").scalar() != 1:
                raise SyntheticFileRefused("TARGET_FK_DISABLED")
            db.commit()
            tx = db.begin()
            try:
                users = subset.tables["users"]
                patients = subset.tables["patients"]
                appointments = subset.tables["appointments"]
                db.execute(users.insert().values(
                    id=777,email="synthetic-owner-777@example.invalid",
                    hashed_password="FAKE_ONLY",role="DENTISTE",
                    is_active=True,is_licensed=False
                ))
                by_source_id = {}
                for old_id, first, last, dob, sex, email in ps:
                    new_id = db.execute(patients.insert().values(
                        employer_id=777,
                        numero_dossier="SYN-%05d" % old_id,
                        prenom=first,nom=last,
                        date_naissance=datetime.strptime(dob,"%Y-%m-%d"),
                        sexe=sex,email=email
                    )).inserted_primary_key[0]
                    by_source_id[old_id] = new_id
                expected_links = []
                for _old_appt, old_patient, when, _status in aps:
                    patient_id = by_source_id.get(old_patient)
                    if patient_id is None:
                        raise SyntheticFileRefused("ORPHAN_SOURCE_REFERENCE")
                    # Explicit ownership validation: target ORM FKs alone
                    # cannot enforce equal patient/appointment employer IDs.
                    owner = db.execute(select(patients.c.employer_id).where(
                        patients.c.id == patient_id, patients.c.deleted_at.is_(None)
                    )).scalar_one_or_none()
                    if owner != 777:
                        raise SyntheticFileRefused("CROSS_TENANT_LINK_REFUSED")
                    parsed = datetime.strptime(when,"%Y-%m-%d %H:%M")
                    db.execute(appointments.insert().values(
                        patient_id=patient_id,employer_id=777,
                        datetime_start=parsed,status="PREVU"
                    ))
                    expected_links.append((patient_id,parsed))
                actual_links = db.execute(select(
                    appointments.c.patient_id, appointments.c.datetime_start
                )).all()
                if sorted(actual_links) != sorted(expected_links):
                    raise SyntheticFileRefused("SYNTHETIC_LINK_PARITY_FAILURE")
                patient_rows = db.execute(select(func.count()).select_from(patients)).scalar_one()
                appt_rows = db.execute(select(func.count()).select_from(appointments)).scalar_one()
                orphan = db.execute(text(
                    "SELECT COUNT(*) FROM appointments a LEFT JOIN patients p "
                    "ON p.id=a.patient_id WHERE p.id IS NULL"
                )).scalar_one()
                cross = db.execute(text(
                    "SELECT COUNT(*) FROM appointments a JOIN patients p "
                    "ON p.id=a.patient_id WHERE p.employer_id!=a.employer_id"
                )).scalar_one()
                if (patient_rows,appt_rows,orphan,cross)!=(100,200,0,0):
                    raise SyntheticFileRefused("TARGET_PARITY_FAILED")
                if db.exec_driver_sql("PRAGMA foreign_key_check").fetchall():
                    raise SyntheticFileRefused("TARGET_FK_CHECK_FAILED")
            finally:
                tx.rollback()
            left_patients = db.execute(select(func.count()).select_from(
                subset.tables["patients"])).scalar_one()
            left_appointments = db.execute(select(func.count()).select_from(
                subset.tables["appointments"])).scalar_one()
            left_users = db.execute(select(func.count()).select_from(
                subset.tables["users"])).scalar_one()
            if (left_patients,left_appointments,left_users)!=(0,0,0):
                raise SyntheticFileRefused("SCRATCH_ROLLBACK_FAILED")
            return SyntheticFileResult(
                "OFFICIAL_SYNTHETIC_SQLITE_FILE_ONLY",
                sha256(payload).hexdigest(),
                100,200,100,200,200,0,0,0,0
            ).to_dict()
    finally:
        engine.dispose()
