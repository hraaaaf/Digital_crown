"""DC-DOS-01: real PDF bytes in existing synthetic archives, A/B/foreign cabinet.

This is NOT a clinical signing test. All identities are generated by the
in-memory SQLite pytest fixture and all PDF files stay under tmp_path.
"""
from __future__ import annotations

import hashlib
import os

import fitz

from backend import models
from backend.tests.conftest import make_user
from backend.tests.p2ter_bridge_synthetic_support import (
    _cabinet, _case, _jwt, _seed_synthetic_historical_cephalo_archive,
)


def _synthetic_pdf(marker: str) -> bytes:
    with fitz.open() as pdf:
        page = pdf.new_page()
        page.insert_text(
            (60, 80),
            "SYNTHETIC TEST ONLY - NO CLINICAL AUTHORITY - " + marker,
        )
        return pdf.tobytes(garbage=4, deflate=True)


def test_dc_dos01_historical_pdf_a_b_x_authenticated_bytes_and_patient_lists(
    client, db, dentiste, monkeypatch, tmp_path,
):
    """A/B see their own real PDF, X cannot fetch them by URL or document ID."""
    from backend.core import media_paths
    from backend.routers import documents
    from backend.services import archive_service

    assert os.environ.get("ENVIRONMENT") == "test"
    assert os.environ.get("DIGITALCROWN_ISOLATED_RUNTIME") in {"true", "1"}
    assert os.environ["DATABASE_URL"] == "sqlite:///:memory:"

    media_root = tmp_path / "dc_dos01_synthetic_media"
    monkeypatch.setattr(archive_service, "ARCHIVE_BASE_DIR", media_root / "archives")
    monkeypatch.setattr(archive_service, "MEDIA_DIR", media_root)
    monkeypatch.setattr(documents, "MEDIA_DIR", media_root)
    monkeypatch.setattr(media_paths, "get_media_root", lambda: media_root)

    _cabinet(db, dentiste)
    patient_a, study_a, _ = _case(db, dentiste)
    patient_b, study_b, _ = _case(db, dentiste)
    foreign = make_user(
        db, email="dc-dos01-foreign-only@cabinet.invalid", role="DENTISTE",
    )
    _cabinet(db, foreign)
    patient_x, study_x, _ = _case(db, foreign)
    assert len({patient_a.id, patient_b.id, patient_x.id}) == 3

    cases = {}
    for name, patient, study in (
        ("A", patient_a, study_a),
        ("B", patient_b, study_b),
        ("X", patient_x, study_x),
    ):
        pdf_bytes = _synthetic_pdf("DC-DOS01-" + name)
        doc, stored_bytes = _seed_synthetic_historical_cephalo_archive(
            db, patient, study,
            filename=f"synthetic-dos01-{name.lower()}.pdf",
            pdf_bytes=pdf_bytes,
        )
        assert doc.document_type == models.DocumentType.RAPPORT_CEPHALO
        assert stored_bytes == pdf_bytes
        assert doc.file_hash == hashlib.sha256(pdf_bytes).hexdigest()
        assert (media_root / doc.file_path.removeprefix("static/")).read_bytes() == pdf_bytes
        with fitz.open(stream=pdf_bytes, filetype="pdf") as opened:
            assert len(opened) == 1
            assert "DC-DOS01-" + name in opened[0].get_text()
        cases[name] = (patient, doc, pdf_bytes)

    assert len({cases[name][2] for name in cases}) == 3

    def read_own(headers, name):
        patient, doc, expected = cases[name]
        index = client.get(f"/api/patients/{patient.id}/documents", headers=headers)
        assert index.status_code == 200, (name, index.status_code, index.text[:250])
        entries = index.json()
        assert [item["id"] for item in entries] == [str(doc.id)]
        assert entries[0]["file_exists"] is True
        assert "static/archives/" in entries[0]["url"]
        for other in cases:
            if other != name:
                assert str(cases[other][1].id) not in {
                    item["id"] for item in entries
                }
        direct = f"/api/documents/{doc.id}/download"
        static = "/api/static/archives/" + doc.file_path.removeprefix("static/archives/")
        for url in (direct, static):
            response = client.get(url, headers=headers)
            assert response.status_code == 200, (name, url, response.status_code, response.text[:200])
            assert response.headers["content-type"].startswith("application/pdf")
            assert response.content == expected
            assert hashlib.sha256(response.content).hexdigest() == doc.file_hash

    def deny_foreign(headers, name):
        patient, doc, expected = cases[name]
        routes = (
            f"/api/patients/{patient.id}/documents",
            f"/api/documents/{doc.id}/download",
            "/api/static/archives/" + doc.file_path.removeprefix("static/archives/"),
        )
        for url in routes:
            response = client.get(url, headers=headers)
            assert response.status_code in (403, 404), (
                name, url, response.status_code, response.text[:200],
            )
            assert response.content != expected

    owner_headers = _jwt(client, dentiste)
    assert client.get("/api/workstation/state", headers=owner_headers).status_code == 200
    read_own(owner_headers, "A")
    read_own(owner_headers, "B")
    deny_foreign(owner_headers, "X")

    foreign_headers = _jwt(client, foreign)
    assert client.get("/api/workstation/state", headers=foreign_headers).status_code == 200
    read_own(foreign_headers, "X")
    deny_foreign(foreign_headers, "A")
    deny_foreign(foreign_headers, "B")

    # Archive creation via unsigned clinical HTTP remains forbidden. This test
    # never signs any PDF or invokes the official archive=true endpoint.
    assert db.query(models.DocumentArchive).count() == 3
