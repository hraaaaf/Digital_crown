import fs from 'node:fs';
import path from 'node:path';
import { chromium, request } from 'playwright';

const outDir = path.resolve('../artifacts/media-c4');
fs.mkdirSync(outDir, { recursive: true });

const runtimeSource = fs.readFileSync('../scripts/t2_runtime_server.py', 'utf8');
const emailMatch = runtimeSource.match(/email="([^"]+)"/);
const passwordMatch = runtimeSource.match(/get_password_hash\("([^"]+)"\)/);
if (!emailMatch || !passwordMatch) throw new Error('C4 could not resolve isolated T2 test credentials');

const viewports = [
  { width: 390, height: 844 },
  { width: 768, height: 1024 },
  { width: 1280, height: 900 },
];

const api = await request.newContext({ baseURL: 'http://127.0.0.1:8005' });
const login = await api.post('/api/auth/login', {
  form: { username: emailMatch[1], password: passwordMatch[1] },
});
if (!login.ok()) throw new Error(`C4 login failed: ${login.status()} ${await login.text()}`);
const tokens = await login.json();
const headers = { Authorization: `Bearer ${tokens.access_token}` };

const patients = await api.get('/api/patients', { headers });
if (!patients.ok()) throw new Error(`C4 patients failed: ${patients.status()} ${await patients.text()}`);
const patient = (await patients.json()).find((row) => row.numero_dossier === 'T2-0001');
if (!patient) throw new Error('C4 fixture patient T2-0001 missing');

const ortho = await api.patch(`/api/patients/${patient.id}/ortho`, {
  headers,
  data: { is_ortho_active: true },
});
if (!ortho.ok()) throw new Error(`C4 ortho activation failed: ${ortho.status()} ${await ortho.text()}`);

// 64x64 RGB PNG generated by Pillow. Keep the fixture parser-valid because C3 intentionally
// rejects malformed image payloads instead of trusting a .png extension.
const validPng = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAEAAAABACAIAAAAlC+aJAAAAY0lEQVR4nO3PQQ3AIADAQEANmpCD8ongcVnSU9DOfe74s6UDXjWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgNaA1oDWgfUJxAYTIfIvQAAAAAElFTkSuQmCC', 'base64');
for (const [timepoint, assetType] of [['T0', 'PHOTO'], ['T1', 'RADIOGRAPH']]) {
  const upload = await api.post(`/api/patients/${patient.id}/assets/import`, {
    headers,
    multipart: {
      file: { name: `c4-${timepoint.toLowerCase()}.png`, mimeType: 'image/png', buffer: validPng },
      asset_type: assetType,
      source_kind: 'UPLOAD',
      timepoint,
    },
  });
  if (!upload.ok()) throw new Error(`C4 ${timepoint} import failed: ${upload.status()} ${await upload.text()}`);
}

const timeline = await api.get(`/api/patients/${patient.id}/assets`, { headers });
if (!timeline.ok()) throw new Error(`C4 timeline failed: ${timeline.status()} ${await timeline.text()}`);
const timelineBody = await timeline.json();
if (!Array.isArray(timelineBody.items) || timelineBody.items.length !== 2) throw new Error('C4 primary timeline count mismatch');
if (timelineBody.items.some((item) => item.source_kind === 'DERIVED')) throw new Error('C4 DERIVED asset leaked into primary timeline');
if (timelineBody.items.some((item) => 'storage_key' in item || 'sha256' in item)) throw new Error('C4 storage secret leaked into timeline');

const browser = await chromium.launch({ headless: true });
const evidence = [];

async function seedAuth(page) {
  await page.addInitScript(({ access, refresh }) => {
    localStorage.setItem('token', access);
    localStorage.setItem('refresh_token', refresh || '');
    localStorage.setItem('appMode', 'prod');
  }, { access: tokens.access_token, refresh: tokens.refresh_token });
}

async function capture(page, viewport, surface, ready) {
  await ready();
  await page.waitForTimeout(450);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 2);
  const shot = `c4-after-${surface}-${viewport.width}x${viewport.height}.png`;
  await page.screenshot({ path: path.join(outDir, shot), fullPage: false });
  return { shot, overflow };
}

for (const viewport of viewports) {
  const context = await browser.newContext({ viewport, colorScheme: 'light' });
  const page = await context.newPage();
  await seedAuth(page);
  const pageErrors = [];
  const http5xx = [];
  page.on('pageerror', (error) => pageErrors.push(String(error)));
  page.on('response', (response) => {
    if (response.status() >= 500) http5xx.push({ url: response.url(), status: response.status() });
  });

  const patientUrl = `http://127.0.0.1:5173/patients/${patient.id}`;
  await page.goto(patientUrl, { waitUntil: 'networkidle', timeout: 90000 });
  await page.getByRole('button', { name: 'Imagerie', exact: true }).click();

  const mediaTab = page.getByRole('button', { name: 'Médiathèque', exact: true });
  const rvgTab = page.getByRole('button', { name: 'RVG', exact: true });
  const panoTab = page.getByRole('button', { name: 'Panoramique', exact: true });
  const cephTab = page.getByRole('button', { name: 'Céphalométrie', exact: true });
  for (const tab of [mediaTab, rvgTab, panoTab, cephTab]) await tab.waitFor({ state: 'visible', timeout: 30000 });

  const surfaces = [];

  await mediaTab.click();
  surfaces.push({ surface: 'imaging-media', ...(await capture(page, viewport, 'imaging-media', async () => {
    await page.getByText('Médiathèque clinique', { exact: true }).waitFor({ state: 'visible', timeout: 30000 });
    await page.getByText('T0', { exact: true }).first().waitFor({ state: 'visible', timeout: 30000 });
    await page.getByText('T1', { exact: true }).first().waitFor({ state: 'visible', timeout: 30000 });
    if (await page.getByText('Médiathèque indisponible', { exact: true }).count()) throw new Error('C4 media timeline entered error state');
  })) });

  const firstAsset = page.getByRole('button', { name: /Ouvrir (Photo|Radiographie)/ }).first();
  await firstAsset.click();
  await page.getByRole('dialog', { name: 'Visionneuse média clinique' }).waitFor({ state: 'visible', timeout: 30000 });
  await page.getByRole('button', { name: 'Fermer la visionneuse' }).click();

  await rvgTab.click();
  surfaces.push({ surface: 'imaging-rvg', ...(await capture(page, viewport, 'imaging-rvg', async () => {
    await page.getByText(/Radiographies intra-orales|Radios intra-orales|RVG/i).first().waitFor({ state: 'visible', timeout: 30000 });
  })) });

  await panoTab.click();
  surfaces.push({ surface: 'imaging-panoramic', ...(await capture(page, viewport, 'imaging-panoramic', async () => {
    await page.getByText('Repérage dentaire automatique · validation praticien', { exact: true }).waitFor({ state: 'visible', timeout: 30000 });
  })) });

  await cephTab.click();
  surfaces.push({ surface: 'imaging-cephalo', ...(await capture(page, viewport, 'imaging-cephalo', async () => {
    await page.getByText('Studio Céphalométrique', { exact: true }).waitFor({ state: 'visible', timeout: 30000 });
  })) });

  evidence.push({ viewport, surfaces, pageErrors, http5xx });
  await context.close();
}

await browser.close();
await api.dispose();

const invalid = evidence.flatMap((row) => [
  ...row.surfaces.filter((surface) => surface.overflow).map((surface) => ({ viewport: row.viewport, surface: surface.surface, reason: 'overflow' })),
  ...row.pageErrors.map((error) => ({ viewport: row.viewport, reason: 'pageerror', error })),
  ...row.http5xx.map((response) => ({ viewport: row.viewport, reason: 'http5xx', ...response })),
]);
const captures = evidence.reduce((total, row) => total + row.surfaces.length, 0);
const summary = {
  status: captures === 12 && invalid.length === 0 ? 'PASS' : 'FAIL',
  captures,
  expectedCaptures: 12,
  surfacesPerViewport: 4,
  viewports,
  invalid,
  timelinePrimaryCount: timelineBody.items.length,
};
fs.writeFileSync(path.join(outDir, 'evidence.json'), JSON.stringify(evidence, null, 2));
fs.writeFileSync(path.join(outDir, 'summary.json'), JSON.stringify(summary, null, 2));
console.log('MEDIA_C4_CERTIFICATION', JSON.stringify(summary));
if (summary.status !== 'PASS') process.exit(1);
